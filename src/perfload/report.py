"""Markdown and self-contained HTML reports."""

import base64
import html
from pathlib import Path

from perfload.metrics import MetricsSummary
from perfload.profiles import PROFILE_DESCRIPTIONS

_GRAPH_FILES = (
    ("response_time_over_time.png", "Response time over time"),
    ("percentiles.png", "Response time percentiles"),
    ("rps_over_time.png", "Requests per second"),
    ("error_rate_over_time.png", "Error rate over time"),
)


def _ms(value: float) -> str:
    return f"{value:.2f}"


def _num(value: float) -> str:
    return f"{value:.3f}"


def _bytes(value: float) -> str:
    return f"{value:.1f}"


def _pct(value: float) -> str:
    return f"{value:.2f}%"


def render_markdown(meta: dict, summary: MetricsSummary) -> str:
    """Build the Markdown report body."""
    profile = str(meta.get("profile", ""))
    description = PROFILE_DESCRIPTIONS.get(profile, "")
    lines = [
        "# Performance test report",
        "",
        f"Generated by perfload {meta.get('version', '')}.",
        "",
        "## Run",
        "",
        f"- Profile: `{profile}` — {description}",
        f"- Target: `{meta.get('base_url', '')}`",
        f"- Virtual users: {meta.get('users')}",
        f"- Spawn rate: {meta.get('spawn_rate')} users/second",
        f"- Requested duration: {meta.get('duration_seconds')}s",
        f"- Wall clock: {_ms(summary.elapsed_seconds)}s",
        f"- Started: {meta.get('started_at', '')}",
        f"- Finished: {meta.get('finished_at', '')}",
        f"- Python: {meta.get('python', '')}",
        f"- Platform: {meta.get('platform', '')}",
        f"- Locust: {meta.get('locust', '')}",
        f"- Concurrency: {meta.get('concurrency_model', '')}",
        "",
        "### Stage plan",
        "",
        "| Until (s) | Users | Spawn rate |",
        "| ---: | ---: | ---: |",
    ]
    for stage in meta.get("stages", []):
        lines.append(
            f"| {stage['end']:.1f} | {stage['users']} | {stage['spawn_rate']} |"
        )
    lines.extend(
        [
            "",
            "## Metrics",
            "",
            "Latency percentiles include every completed request. "
            "Requests per second and throughput divide totals by the runner wall clock. "
            "Percentiles use pandas linear interpolation.",
            "",
            "| Metric | Value |",
            "| --- | ---: |",
            f"| Total requests | {summary.total_requests} |",
            f"| Successful | {summary.successful} |",
            f"| Failed | {summary.failed} |",
            f"| Error percentage | {_pct(summary.error_percentage)} |",
            f"| Average response time (ms) | {_ms(summary.average_ms)} |",
            f"| Median response time (ms) | {_ms(summary.median_ms)} |",
            f"| P90 (ms) | {_ms(summary.p90_ms)} |",
            f"| P95 (ms) | {_ms(summary.p95_ms)} |",
            f"| P99 (ms) | {_ms(summary.p99_ms)} |",
            f"| Min response time (ms) | {_ms(summary.min_ms)} |",
            f"| Max response time (ms) | {_ms(summary.max_ms)} |",
            f"| Requests per second | {_num(summary.requests_per_second)} |",
            f"| Throughput (response bytes/s) | {_bytes(summary.throughput_bytes_per_second)} |",
            "",
            "## Endpoints",
            "",
            "| Endpoint | Total | Failed | Error % | Avg ms | Median ms | P95 ms | RPS |",
            "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
        ]
    )
    for endpoint in summary.endpoints:
        lines.append(
            f"| {endpoint.name} | {endpoint.total} | {endpoint.failed} | "
            f"{_pct(endpoint.error_percentage)} | {_ms(endpoint.average_ms)} | "
            f"{_ms(endpoint.median_ms)} | {_ms(endpoint.p95_ms)} | "
            f"{_num(endpoint.requests_per_second)} |"
        )
    lines.extend(["", "## Errors", ""])
    if not summary.errors:
        lines.append("No failed requests.")
    else:
        lines.extend(
            [
                "| Category | Key | Count | Share of requests |",
                "| --- | --- | ---: | ---: |",
            ]
        )
        for error in summary.errors:
            lines.append(
                f"| {error.category} | {error.key} | {error.count} | {_pct(error.percentage)} |"
            )
    lines.extend(["", "## Graphs", ""])
    for filename, title in _GRAPH_FILES:
        lines.append(f"### {title}")
        lines.append("")
        lines.append(f"![{title}](graphs/{filename})")
        lines.append("")
    lines.append("Locust's own HTML report is `locust-report.html` in this directory.")
    lines.append("")
    return "\n".join(lines)


def render_html(meta: dict, summary: MetricsSummary, graph_dir: Path) -> str:
    """Build a single HTML file with the charts embedded."""
    markdown_metrics = render_markdown(meta, summary)
    # The HTML layout is independent; the Markdown renderer stays the source of
    # the same numbers, formatted again below so the file is readable alone.
    rows = [
        ("Total requests", str(summary.total_requests)),
        ("Successful", str(summary.successful)),
        ("Failed", str(summary.failed)),
        ("Error percentage", _pct(summary.error_percentage)),
        ("Average response time (ms)", _ms(summary.average_ms)),
        ("Median response time (ms)", _ms(summary.median_ms)),
        ("P90 (ms)", _ms(summary.p90_ms)),
        ("P95 (ms)", _ms(summary.p95_ms)),
        ("P99 (ms)", _ms(summary.p99_ms)),
        ("Min response time (ms)", _ms(summary.min_ms)),
        ("Max response time (ms)", _ms(summary.max_ms)),
        ("Requests per second", _num(summary.requests_per_second)),
        ("Throughput (response bytes/s)", _bytes(summary.throughput_bytes_per_second)),
    ]
    metric_rows = "\n".join(
        f"<tr><th>{html.escape(label)}</th><td>{html.escape(value)}</td></tr>"
        for label, value in rows
    )
    endpoint_rows = "\n".join(
        "<tr>"
        f"<td>{html.escape(item.name)}</td>"
        f"<td>{item.total}</td><td>{item.failed}</td>"
        f"<td>{html.escape(_pct(item.error_percentage))}</td>"
        f"<td>{html.escape(_ms(item.average_ms))}</td>"
        f"<td>{html.escape(_ms(item.median_ms))}</td>"
        f"<td>{html.escape(_ms(item.p95_ms))}</td>"
        f"<td>{html.escape(_num(item.requests_per_second))}</td>"
        "</tr>"
        for item in summary.endpoints
    )
    if summary.errors:
        error_rows = "\n".join(
            "<tr>"
            f"<td>{html.escape(item.category)}</td>"
            f"<td>{html.escape(item.key)}</td>"
            f"<td>{item.count}</td>"
            f"<td>{html.escape(_pct(item.percentage))}</td>"
            "</tr>"
            for item in summary.errors
        )
        error_table = (
            "<table><thead><tr><th>Category</th><th>Key</th><th>Count</th>"
            "<th>Share of requests</th></tr></thead>"
            f"<tbody>{error_rows}</tbody></table>"
        )
    else:
        error_table = "<p>No failed requests.</p>"
    figures = []
    for filename, title in _GRAPH_FILES:
        image = graph_dir / filename
        if not image.is_file():
            continue
        encoded = base64.b64encode(image.read_bytes()).decode("ascii")
        figures.append(
            "<figure>"
            f"<img alt='{html.escape(title)}' src='data:image/png;base64,{encoded}' />"
            f"<figcaption>{html.escape(title)}</figcaption></figure>"
        )
    profile = html.escape(str(meta.get("profile", "")))
    description = html.escape(PROFILE_DESCRIPTIONS.get(str(meta.get("profile", "")), ""))
    fault = meta.get("target_fault_injection") or {}
    fault_line = html.escape(
        "latency_ms={latency}, jitter_ms={jitter}, error_rate={rate}".format(
            latency=fault.get("latency_ms", "n/a"),
            jitter=fault.get("jitter_ms", "n/a"),
            rate=fault.get("error_rate", "n/a"),
        )
    )
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>perfload report</title>
  <style>
    body {{ font-family: "Segoe UI", Helvetica, Arial, sans-serif; margin: 2rem auto;
            max-width: 980px; color: #24292f; line-height: 1.45; }}
    h1 {{ margin-bottom: 0.2rem; }}
    .muted {{ color: #57606a; }}
    table {{ border-collapse: collapse; width: 100%; margin: 1rem 0 1.5rem; }}
    th, td {{ border-bottom: 1px solid #d0d7de; text-align: left; padding: 0.4rem 0.5rem; }}
    td {{ text-align: right; }}
    td:first-child, th:first-child {{ text-align: left; }}
    img {{ max-width: 100%; height: auto; }}
    figure {{ margin: 1.2rem 0; }}
    figcaption {{ color: #57606a; font-size: 0.9rem; }}
    code {{ background: #f6f8fa; padding: 0.1rem 0.3rem; }}
  </style>
</head>
<body>
  <h1>Performance test report</h1>
  <p class="muted">perfload {html.escape(str(meta.get("version", "")))}
  · {html.escape(str(meta.get("started_at", "")))}</p>
  <h2>Run</h2>
  <ul>
    <li>Profile: <code>{profile}</code> — {description}</li>
    <li>Target: <code>{html.escape(str(meta.get("base_url", "")))}</code></li>
    <li>Virtual users: {html.escape(str(meta.get("users", "")))}</li>
    <li>Spawn rate: {html.escape(str(meta.get("spawn_rate", "")))} users/second</li>
    <li>Requested duration: {html.escape(str(meta.get("duration_seconds", "")))}s</li>
    <li>Wall clock: {html.escape(_ms(summary.elapsed_seconds))}s</li>
    <li>Python {html.escape(str(meta.get("python", "")))}
        · Locust {html.escape(str(meta.get("locust", "")))}</li>
    <li>Platform: {html.escape(str(meta.get("platform", "")))}</li>
    <li>Fault injection env seen by the runner: {fault_line}</li>
  </ul>
  <h2>Metrics</h2>
  <table><tbody>
  {metric_rows}
  </tbody></table>
  <h2>Endpoints</h2>
  <table>
    <thead><tr><th>Endpoint</th><th>Total</th><th>Failed</th><th>Error %</th>
    <th>Avg ms</th><th>Median ms</th><th>P95 ms</th><th>RPS</th></tr></thead>
    <tbody>{endpoint_rows}</tbody>
  </table>
  <h2>Errors</h2>
  {error_table}
  <h2>Graphs</h2>
  {"".join(figures)}
  <p class="muted">The same figures are saved as PNG files under graphs/.
  Locust's report is locust-report.html. A Markdown copy is report.md.</p>
  <!-- markdown twin is generated separately; length {len(markdown_metrics)} -->
</body>
</html>
"""


def write_reports(meta: dict, summary: MetricsSummary, output_dir: Path) -> tuple[Path, Path]:
    """Write report.md and report.html. Returns both paths."""
    graph_dir = output_dir / "graphs"
    markdown = render_markdown(meta, summary)
    document = render_html(meta, summary, graph_dir)
    markdown_path = output_dir / "report.md"
    html_path = output_dir / "report.html"
    markdown_path.write_text(markdown, encoding="utf-8")
    html_path.write_text(document, encoding="utf-8")
    return markdown_path, html_path
